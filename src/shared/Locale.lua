local current = "pt-BR"

function Locale.SetLanguage(language: string)
	if strings[language] then
		current = language
	end
end

function Locale.t(key: string, ...: any): string
	local template = (strings[current] and strings[current][key]) or strings["pt-BR"][key] or key
	if select("#", ...) == 0 then
		return template
	end
	local ok, text = pcall(string.format, template, ...)
	return ok and text or template
end

return Locale
